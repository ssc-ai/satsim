CONFIG_PATH = Path(__file__).parent / 'config_passive_rf.json'


def _run_config(**changes):
    document = transform(
        load_json(str(CONFIG_PATH)),
        dirname=str(CONFIG_PATH.parent),
    )
    config = load_run_config(document)
    return dataclasses.replace(config, **changes)


def test_measurement_kernel_matches_prototype_golden_vector():
    """Golden values were generated by the handoff prototype with seed 42."""
    config = _run_config()
    request = config.observations[0]
    target = config.targets[request.target_id]
    satellite = config.target_objects[request.target_id]
    geometries = []
    for receiver_id in (request.sensor1, request.sensor2):
        geometries.append(receiver_geometry(
            config.observers[receiver_id],
            satellite,
            request.time,
        ))
    record = simulate_measurement(
        target,
        config.receivers[request.sensor1],
        config.receivers[request.sensor2],
        config.estimator,
        request.time,
        random.Random(42),
        geometries[0],
        geometries[1],
    )
    assert record['snrRawDb'] == pytest.approx(39.028, abs=0.001)
    assert record['snrProcessedDb'] == pytest.approx(70.008, abs=0.001)
    assert record['snr'] == pytest.approx(db_to_lin(record['snrProcessedDb']))
    assert record['tdoaTrue'] == pytest.approx(0.0009976404761496479, abs=1e-18)
    assert record['fdoaTrue'] == pytest.approx(-1963.8066386465944, abs=1e-10)
    assert record['tdoaUnc'] == pytest.approx(1.20025282457185e-08, rel=1e-14)
    assert record['fdoaUnc'] == pytest.approx(0.0030002107019385265, rel=1e-14)
    assert record['tdoa'] == pytest.approx(0.0009976387467013972, abs=1e-18)
    assert record['fdoa'] == pytest.approx(-1963.8071573938264, abs=1e-10)
    assert record['band'] == 'S-band'
    assert 'seed' not in record
    assert 'sigma_tdoa_s' not in record
    assert 'sigma_fdoa_hz' not in record
    assert 'dataMode' not in record
    assert 'createdAt' not in record

    # The standard SatSim Earth-centered geometry remains within 0.1 ns TDOA
    # and 0.2 mHz FDOA of the private prototype geometry.
    assert record['tdoaTrue'] == pytest.approx(
        0.0009976405262695578,
        abs=1.0e-10,
    )
    assert record['fdoaTrue'] == pytest.approx(
        -1963.8067461204773,
        abs=2.0e-4,
    )


def test_native_measurement_seed_is_repeatable():
    config = _run_config()
    first = simulate_run_config(config)
    second = simulate_run_config(config)
    assert first == second
    assert all(record['type'] == 'PASSIVE_RF' for record in first)
    assert all(record['uct'] is False for record in first)
    assert all('seed' not in record for record in first)


def test_unrelated_insertion_does_not_perturb_existing_measurements():
    config = _run_config()
    baseline = simulate_run_config(config)
    original = config.observations[0]
    inserted = dataclasses.replace(
        original,
        time=time.utc_from_list([2020, 1, 29, 13, 9, 59.5], delta_sec=-0.5),
        source_index=999,
    )
    extended = dataclasses.replace(
        config,
        observations=config.observations + (inserted,),
    )
    extended_records = simulate_run_config(extended)
    baseline_by_key = {
        (record['obTime'], record['idSensor1'], record['idSensor2']): record
        for record in baseline
    }
    extended_by_key = {
        (record['obTime'], record['idSensor1'], record['idSensor2']): record
        for record in extended_records
    }
    for key, record in baseline_by_key.items():
        assert extended_by_key[key] == record


