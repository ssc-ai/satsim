def test_site_link_snr():
    target = TargetRFParams(1, 2.2e9, 500000.0, 45.0)
    receiver = ReceiverParams('A', 30.0, 2.0, 1.0, 290.0)
    expected = (
        45.0 + 30.0 - core.fspl_db(2.2e9, 4.0e7) - 1.0 -
        core.noise_power_dbw(500000.0, 2.0, 290.0)
    )
    assert core.receiver_snr_db(target, receiver, 4.0e7) == pytest.approx(expected)


def test_estimator_uses_max_pair_level_override():
    target = TargetRFParams(1, 2.2e9, 500000.0, 45.0)
    estimator = EstimatorParams(
        tdoa_floor_s=1e-9,
        fdoa_floor_hz=1e-3,
        tdoa_floor_by_sensor={'A': 2e-8, 'B': 1e-8},
        fdoa_floor_by_sensor={'A': 0.02, 'B': 0.01},
    )
    tdoa, fdoa = core.measurement_uncertainties(
        target, estimator, 'A', 'B', 100.0
    )
    assert tdoa >= 2e-8
    assert fdoa >= 0.02
    np.testing.assert_allclose(
        core.combine_sensor_value(1.0, {'A': 2.0, 'B': 3.0}, 'A', 'B'),
        3.0,
    )


def test_standard_satsim_target_observer_and_los_geometry():
    config = _run_config()
    request = config.observations[0]
    target = config.target_objects[request.target_id]
    observer = config.observers[request.sensor1]

    geometry = receiver_geometry(observer, target, request.time)

    assert geometry.range_m > 0.0
    assert abs(geometry.range_rate_m_s) < 20000.0
    assert 0.0 <= geometry.azimuth_deg <= 360.0
    assert -90.0 <= geometry.elevation_deg <= 90.0


def test_run_resolves_standard_geometry_once_per_target_receiver_epoch(monkeypatch):
    import satsim.passive_rf.model as model

    config = _run_config()
    geometry_calls = []

    def build_geometry(observer, target, t):
        geometry_calls.append((observer, target, t.utc_iso()))
        return ReceiverGeometry(1.0e6, 0.0, 45.0, -45.0)

    monkeypatch.setattr(model, 'receiver_geometry', build_geometry)

    records = simulate_run_config(
        config,
        target_objects={25544: 'target'},
        observer_objects={name: name for name in config.receivers},
    )

    assert len(geometry_calls) == 6
    assert len(records) == 6
