def test_db_conversions_round_trip():
    assert core.db_to_lin(10.0) == pytest.approx(10.0)
    assert core.lin_to_db(10.0) == pytest.approx(10.0)
    assert core.lin_to_db(core.db_to_lin(-17.3)) == pytest.approx(-17.3)


@pytest.mark.parametrize('value', [0.0, -1.0, math.inf, math.nan])
def test_lin_to_db_rejects_invalid_values(value):
    with pytest.raises(ValueError, match='positive and finite'):
        core.lin_to_db(value)


def test_fspl_matches_closed_form_and_rejects_invalid_values():
    expected = 20.0 * math.log10(
        4.0 * math.pi * 1.0e6 * 2.2e9 / core.C_M_S
    )
    assert core.fspl_db(2.2e9, 1.0e6) == pytest.approx(expected)
    with pytest.raises(ValueError, match='Range'):
        core.fspl_db(2.2e9, 0.0)
    with pytest.raises(ValueError, match='Frequency'):
        core.fspl_db(0.0, 1.0)


def test_noise_power():
    expected = 10.0 * math.log10(core.K_B * 290.0 * 1.0e6)
    assert core.noise_power_dbw(1.0e6, 0.0, 290.0) == pytest.approx(expected)
    with pytest.raises(ValueError, match='Bandwidth'):
        core.noise_power_dbw(0.0, 0.0)


def test_effective_pair_snr_and_processing_gain():
    assert core.effective_snr_db(20.0, 20.0) == pytest.approx(
        20.0 - 10.0 * math.log10(2.0)
    )
    assert core.processing_gain_db(500000.0, 0.005) == pytest.approx(
        10.0 * math.log10(2500.0)
    )
    with pytest.raises(ValueError, match='positive'):
        core.processing_gain_db(1.0, 0.0)


