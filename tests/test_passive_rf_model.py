def test_fixed_fdoa_convention_tracks_tdoa_time_derivative():
    records = simulate_run_config(_run_config())
    pair = [record for record in records if record['idSensor2'] == 'RX_B']
    pair.sort(key=lambda record: record['obTime'])
    derivative = pair[1]['tdoaTrue'] - pair[0]['tdoaTrue']
    expected_midpoint_fdoa = 2.2e9 * derivative
    actual_midpoint_fdoa = 0.5 * (pair[0]['fdoaTrue'] + pair[1]['fdoaTrue'])
    assert actual_midpoint_fdoa == pytest.approx(expected_midpoint_fdoa, abs=0.01)


@pytest.mark.parametrize(('blocked_receiver', 'remaining_pair'), [
    ('RX_A', ('RX_B', 'RX_C')),
    ('RX_C', ('RX_A', 'RX_B')),
])
def test_field_of_view_filters_pairs_at_both_receivers(
    monkeypatch,
    blocked_receiver,
    remaining_pair,
):
    import satsim.passive_rf.model as model

    def geometry(observer, *args, **kwargs):
        elevation = -5.0 if observer == blocked_receiver else 45.0
        return ReceiverGeometry(1.0e6, 0.0, 45.0, elevation)

    monkeypatch.setattr(
        model,
        'receiver_geometry',
        geometry,
    )
    config = _run_config()
    receivers = {
        name: dataclasses.replace(
            receiver,
            az_limits=(0.0, 360.0),
            el_limits=(0.0, 90.0),
        )
        for name, receiver in config.receivers.items()
    }
    config = dataclasses.replace(config, receivers=receivers)
    records = simulate_run_config(
        config,
        target_objects={25544: object()},
        observer_objects={name: name for name in config.receivers},
    )
    assert {
        (record['idSensor1'], record['idSensor2'])
        for record in records
    } == {remaining_pair}


